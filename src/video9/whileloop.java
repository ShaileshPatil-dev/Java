package video9;

public class whileloop {
     public static void main(String[] args) {
          // while loop
          int a = 0;
          while (a < 100) {
               System.out.print(a + " ");
               a++;
          }
          /*
           * intialization
           * while (condition)
           * {
           * when the condition is true
           * incrementation / decrementation
           * }
           * When to use it : when you dont know how many times the loop is going to run
           * eg : take the input/s until the user press x
           */
     }
}
